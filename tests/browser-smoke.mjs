// Dependency-free Chromium smoke test via the Chrome DevTools Protocol.
// Run against npm start: node tests/browser-smoke.mjs
import { spawn } from 'node:child_process';
import { mkdtemp, writeFile, readFile, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';

const browserPath = process.env.CHROME_PATH || '/home/zr/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome';
const base = process.env.TEST_URL || 'http://127.0.0.1:4173';
const profile = await mkdtemp(join(tmpdir(), 'disaster-watch-browser-'));
const browser = spawn(browserPath, ['--headless=new', '--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu', '--remote-debugging-port=0', `--user-data-dir=${profile}`, 'about:blank'], { stdio: ['ignore', 'ignore', 'pipe'] });
let socket;
const errors = [], checks = [];
const check = (label, value) => { assert.ok(value, label); checks.push(label); console.log(`PASS ${label}`); };
const delay = ms => new Promise(r => setTimeout(r, ms));
try {
  const ws = await new Promise((resolve, reject) => {
    let stderr = '';
    const timeout = setTimeout(() => reject(new Error(`Chromium did not start: ${stderr.slice(-1200)}`)), 12000);
    browser.on('error', reject);
    browser.stderr.on('data', chunk => { stderr += chunk; const match = stderr.match(/DevTools listening on (ws:\/\/[^\s]+)/); if (match) { clearTimeout(timeout); resolve(match[1]); } });
    browser.on('exit', code => { clearTimeout(timeout); reject(new Error(`Chromium exited ${code}: ${stderr.slice(-1200)}`)); });
  });
  socket = new WebSocket(ws);
  await new Promise((resolve, reject) => { socket.onopen = resolve; socket.onerror = reject; });
  let next = 0;
  const pending = new Map();
  socket.onmessage = event => {
    const msg = JSON.parse(event.data);
    if (msg.id) { const p = pending.get(msg.id); pending.delete(msg.id); if (msg.error) p?.reject(new Error(JSON.stringify(msg.error))); else p?.resolve(msg.result); }
    if (msg.method === 'Runtime.exceptionThrown') errors.push(msg.params.exceptionDetails.exception?.description || msg.params.exceptionDetails.text);
    if (msg.method === 'Log.entryAdded' && msg.params.entry.level === 'error') errors.push(msg.params.entry.text);
  };
  const send = (method, params = {}, sessionId) => new Promise((resolve, reject) => { const id = ++next; pending.set(id, { resolve, reject }); socket.send(JSON.stringify({ id, method, params, ...(sessionId ? { sessionId } : {}) })); });
  const target = await send('Target.createTarget', { url: 'about:blank' });
  const { sessionId } = await send('Target.attachToTarget', { targetId: target.targetId, flatten: true });
  const call = (method, params) => send(method, params, sessionId);
  await call('Page.enable'); await call('Runtime.enable'); await call('Log.enable');
  await call('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
  await call('Page.addScriptToEvaluateOnNewDocument', { source: 'window.__testOffset=0;const originalFrame=window.requestAnimationFrame.bind(window);window.requestAnimationFrame=callback=>originalFrame(t=>callback(t+window.__testOffset));' });
  const evaluate = async expression => {
    const r = await call('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true });
    if (r.exceptionDetails) throw new Error(r.exceptionDetails.exception?.description || r.exceptionDetails.text);
    return r.result.value;
  };
  const until = async expression => { for (let i = 0; i < 80; i++) { if (await evaluate(expression)) return; await delay(100); } throw new Error(`Timed out: ${expression}`); };
  const click = async selector => {
    const rect = await evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error('Missing click target');e.scrollIntoView({block:'center'});const r=e.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2};})()`);
    await call('Input.dispatchMouseEvent', { type: 'mousePressed', ...rect, button: 'left', clickCount: 1 });
    await call('Input.dispatchMouseEvent', { type: 'mouseReleased', ...rect, button: 'left', clickCount: 1 });
    await delay(100);
  };
  const change = async (selector, value) => { await evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('change',{bubbles:true}));})()`); };
  const advance = async seconds => { await evaluate(`window.__testOffset += ${seconds * 1000}`); await delay(350); };
  const shot = async name => { const { data } = await call('Page.captureScreenshot', { format: 'png', captureBeyondViewport: false }); await writeFile(`artifacts/${name}.png`, Buffer.from(data, 'base64')); };
  await mkdir('artifacts', { recursive: true });
  await call('Page.addScriptToEvaluateOnNewDocument', { source: `window.__spoken=[];Object.defineProperty(window,'speechSynthesis',{value:{getVoices:()=>[],cancel(){},speak(u){window.__spoken.push({text:u.text,lang:u.lang});setTimeout(()=>u.onstart?.(),0);setTimeout(()=>u.onend?.(),1200);}}});` });
  await call('Emulation.setDeviceMetricsOverride', { width: 1366, height: 768, deviceScaleFactor: 1, mobile: false });
  await call('Page.navigate', { url: base });
  await until('document.querySelector("#begin") && !document.querySelector("#begin").disabled');
  await click('#begin');
  await until('document.querySelector("#intro").hidden');
  check('English game starts with every AI function off', await evaluate('document.documentElement.lang === "en" && [...document.querySelectorAll("[data-setting]")].every(b=>b.getAttribute("aria-checked")==="false")'));
  check('No page scrolling at 1366 by 768', await evaluate('document.documentElement.scrollHeight===innerHeight && document.documentElement.scrollWidth===innerWidth'));
  check('Large title and status dashboard are removed', await evaluate('!document.querySelector(".topbar,.statusbar")'));
  check('Exactly four category cards, no duplicate individual-unit selector', await evaluate('document.querySelectorAll(".type-card").length===4 && !document.querySelector("#unit-select")'));
  check('Initial availability is ground 2, boat 2, helicopter 1, drones 10', await evaluate('JSON.stringify([...document.querySelectorAll(".available-count")].map(e=>e.textContent))===JSON.stringify(["×2","×2","×1","×10"])'));
  check('Initial radio is empty', await evaluate('document.querySelectorAll(".chat-row").length===0 && document.querySelector(".radio-empty")?.textContent.includes("Radio clear")'));
  await shot('command-desktop');
  await click('#pause');
  check('Pause covers and obscures the complete game view', await evaluate('!document.querySelector("#pause-screen").hidden && document.querySelector("#pause-title").textContent==="PAUSED" && getComputedStyle(document.querySelector("#pause-screen")).backdropFilter.includes("blur")'));
  await advance(10);
  check('Radio and simulation remain stopped while paused', await evaluate('document.querySelectorAll(".chat-row").length===0 && document.querySelector("#pause").getAttribute("aria-pressed")==="true"'));
  await shot('pause-desktop');
  await call('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape'});await call('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape'});await delay(150);
  check('Escape resumes the paused game', await evaluate('document.querySelector("#pause-screen").hidden && document.querySelector("#pause").getAttribute("aria-pressed")==="false"'));
  const dragTo = async (kind, sector) => {
    const coords={A1:[.105,.105],B1:[.325,.075],C1:[.555,.105],D1:[.795,.082],A2:[.090,.300],B2:[.305,.270],C2:[.555,.305],D2:[.820,.285],A3:[.125,.515],B3:[.350,.485],C3:[.595,.530],D3:[.845,.500],A4:[.105,.725],B4:[.330,.705],C4:[.585,.745],D4:[.825,.715]};
    const [nx,ny]=coords[sector];
    const r=await evaluate(`(()=>{const b=document.querySelector('[data-kind="${kind}"]').getBoundingClientRect();const m=document.querySelector('#map').getBoundingClientRect();const h=m.height-document.querySelector('.evac-strip').offsetHeight-10;return {sx:b.x+b.width/2,sy:b.y+b.height/2,x:m.x+m.width*${nx},y:m.y+h*${ny}};})()`);
    await call('Input.dispatchMouseEvent',{type:'mouseMoved',x:r.sx,y:r.sy});
    await call('Input.dispatchMouseEvent',{type:'mousePressed',x:r.sx,y:r.sy,button:'left',clickCount:1});
    await call('Input.dispatchMouseEvent',{type:'mouseMoved',x:r.x,y:r.y,button:'left',buttons:1});
    await call('Input.dispatchMouseEvent',{type:'mouseReleased',x:r.x,y:r.y,button:'left',clickCount:1});
    await delay(250);
  };
  await advance(5.2);
  check('First radio traffic arrives after the quiet opening', await evaluate('document.querySelectorAll(".chat-row").length>0'));
  await dragTo('drone','A1');
  check('Dragging a drone dispatches it and decrements the category count', await evaluate('document.querySelector("[data-kind=drone] .available-count").textContent==="×9" && document.querySelector("#feedback").textContent.includes("DR-01")'));
  await advance(7);
  check('Colleague speaks English and appears on the left', await evaluate('!document.querySelector("#colleague").hidden && window.__spoken.some(x=>x.lang==="en-US")'));
  await delay(2000);
  check('Colleague bubble fades after the speech ends', await evaluate('document.querySelector("#colleague").hidden'));
  await advance(13);
  check('Drone field verification is reflected in chat', await evaluate('document.querySelector("#report-list").textContent.includes("Field checked")'));
  await advance(6);
  check('Drone becomes available again only after its return', await evaluate('document.querySelector("[data-kind=drone] .available-count").textContent==="×10"'));
  await dragTo('ground','A1');
  check('Dragging a ground vehicle dispatches one eight-seat team', await evaluate('document.querySelector("[data-kind=ground] .available-count").textContent==="×1" && !document.querySelector("#feedback").classList.contains("error-feedback")'));
  await click('#dispatch');
  check('Unavailable assignment gives explicit feedback instead of a dead button', await evaluate('document.querySelector("#feedback").classList.contains("error-feedback")'));
  await advance(16);
  check('Road collision arrives as an actionable chat message', await evaluate('!!document.querySelector("[data-road=RD1]")'));
  await click('[data-road="RD1"]');
  await click('[data-kind="ground"]');
  await click('#dispatch');
  check('Ground crew accepts a road-clearing order', await evaluate('document.querySelector("#feedback").textContent.includes("Collision") && !document.querySelector("#feedback").classList.contains("error-feedback")'));
  await shot('road-response-desktop');
  await advance(50);
  check('Road repair progresses through work and return', await evaluate('document.querySelector("#report-list").textContent.includes("cleared")'));
  await click('[data-setting="filter"]');
  check('Noise filtering removes station chatter and keeps ground traffic', await evaluate('document.querySelectorAll(".chat-row.noise").length===0 && !!document.querySelector("[data-road=RD1]")'));
  await click('[data-kind="drone"]');
  check('Selecting a drone immediately focuses the filtered radio', await evaluate('!document.querySelector("[data-road=RD1]") && document.querySelector("#report-list").textContent.includes("Field sensor")'));
  await click('[data-kind="skiff"]');
  check('Selecting a rescue boat keeps waterfront people and hides general traffic', await evaluate('document.querySelector("#report-list").textContent.includes("West Dock") && !document.querySelector("#report-list").textContent.includes("Colony warning broadcast") && !document.querySelector("[data-road=RD1]")'));
  await click('[data-kind="ground"]');
  await click('[data-setting="filter"]');
  check('Noise returns when filtering is disabled', await evaluate('document.querySelectorAll(".chat-row.noise").length>0'));
  await click('[data-setting="aggregate"]');
  check('Enabling AI aggregation adds evidence to the chat', await evaluate('document.querySelectorAll(".ai-note").length>0'));
  await click('#help');
  await advance(50);
  check('Simulation keeps running while help is open', await evaluate('document.querySelector("#guide").open && document.querySelector("#report-list").textContent.includes("Elder Grove")'));
  await click('#close-guide');
  await click('[data-event="R06"]');
  await click('[data-action="edit"]');
  await change('#correct-priority','high');
  await click('#apply-correction');
  check('Corrections apply inside the expanded report', await evaluate('document.querySelector(".chat-row.expanded .report-details").textContent.includes("Elder Grove") && !document.querySelector("#feedback").classList.contains("error-feedback")'));
  await advance(72);
  check('Relay failure is visible in the compact wifi indicator', await evaluate('document.querySelector("#wifi").classList.contains("offline")'));
  check('The radio panel scrolls while the page remains fixed', await evaluate('document.querySelector("#report-list").scrollHeight>document.querySelector("#report-list").clientHeight && document.documentElement.scrollHeight===innerHeight'));
  await shot('outage-desktop');
  await advance(70);
  check('Compact wifi indicator recovers after the outage', await evaluate('!document.querySelector("#wifi").classList.contains("offline")'));
  await advance(100);
  check('Mission completes with a debrief', await evaluate('!document.querySelector("#debrief").hidden'));
  await send('Browser.setDownloadBehavior',{behavior:'allow',downloadPath:resolve(profile)});
  await click('#export');
  let exported;
  for(let i=0;i<30;i++){try{exported=JSON.parse(await readFile(join(profile,'disaster-watch-review.json')));break;}catch{await delay(100);}}
  check('Review export preserves population accounting',exported?.saved+exported?.lost===exported?.population);
  await shot('debrief-desktop');
  await evaluate('window.__testOffset=0');
  await click('#replay');
  check('Replay restores availability and switches all AI off',await evaluate('document.querySelector("[data-kind=drone] .available-count").textContent==="×10" && [...document.querySelectorAll("[data-setting]")].every(b=>b.getAttribute("aria-checked")==="false")'));
  await dragTo('skiff','A1');
  check('A rescue boat begins on a road trailer bound for a launch site',await evaluate('document.querySelector("[data-kind=skiff] .available-count").textContent==="×1" && document.querySelector("#feedback").textContent.includes("towing to A1")'));
  await dragTo('skiff','A4');
  check('A rescue boat cannot deploy directly into a dry inland sector',await evaluate('document.querySelector("[data-kind=skiff] .available-count").textContent==="×1" && document.querySelector("#feedback").classList.contains("error-feedback") && document.querySelector("#feedback").textContent.includes("not connected to floodwater")'));
  await shot('boat-deployment-desktop');
  await call('Emulation.setDeviceMetricsOverride',{width:1280,height:720,deviceScaleFactor:1,mobile:false});await delay(200);
  check('Full game fits 1280 by 720',await evaluate('document.documentElement.scrollWidth===innerWidth&&document.documentElement.scrollHeight===innerHeight&&document.querySelector("#fleet").getBoundingClientRect().bottom<=innerHeight'));
  await call('Emulation.setDeviceMetricsOverride',{width:1920,height:1080,deviceScaleFactor:1,mobile:false});await delay(200);
  check('Full game fits 1920 by 1080',await evaluate('document.documentElement.scrollHeight===innerHeight'));
  await shot('command-wide');
  await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});await delay(200);
  check('Small view remains fixed without whole-page scrolling',await evaluate('document.documentElement.scrollWidth===innerWidth&&document.documentElement.scrollHeight===innerHeight'));
  await shot('command-mobile');
  check('No browser exceptions or resource failures',errors.length===0);
  await writeFile('artifacts/browser-results.json',JSON.stringify({checks,errors},null,2));
  console.log(`Completed ${checks.length} browser checks.`);
} finally {
  socket?.close(); browser.kill('SIGTERM');
  await delay(500);
  await rm(profile, { recursive: true, force: true }).catch(() => {});
}
